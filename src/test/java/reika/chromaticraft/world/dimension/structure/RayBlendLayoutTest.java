package reika.chromaticraft.world.dimension.structure;

import static org.junit.jupiter.api.Assertions.*;
import java.io.ByteArrayOutputStream;
import java.io.DataOutputStream;
import java.util.HexFormat;
import java.util.List;
import java.util.Random;
import org.junit.jupiter.api.Test;

class RayBlendLayoutTest {
    @Test
    void allAuthoredProfilesSurviveAcrossWidelySpacedSeeds() throws Exception {
        Random seeds = new Random(0x524159424C454E44L);
        for (int i = 0; i < 128; i++) {
            long seed = i == 0 ? Long.MIN_VALUE : i == 1 ? Long.MAX_VALUE : seeds.nextLong();
            int difficulty = 1 + i % 3;
            var layout = RayBlendLayout.create(difficulty, seed, -384, 912);
            assertEquals(RayBlendLayout.profiles(difficulty).length, layout.rooms().size(), "seed=" + seed);
            var twin = RayBlendLayout.create(difficulty, seed, -384, 912);
            assertEquals(fingerprint(layout), fingerprint(twin), "difficulty=" + difficulty + ", seed=" + seed);
            for (int r = 0; r < layout.rooms().size(); r++) {
                var room = layout.rooms().get(r);
                assertEquals(r, room.profileIndex());
                assertEquals(r, room.index());
                assertEquals(RayBlendLayout.profiles(difficulty)[r].gridSize(), room.gridSize());
            }
        }
    }

    @Test
    void unsupportedLayoutVersionsCannotSilentlyRewriteASave() {
        assertThrows(IllegalArgumentException.class, () -> RayBlendLayout.create(-1, 3, 7, 0, 0));
        assertThrows(IllegalArgumentException.class, () -> RayBlendLayout.create(2, 3, 7, 0, 0));
    }

    /** Golden plans independently generated by the committed pre-fix implementation, not version 1. */
    @Test
    void preVersionedSavePlansKeepTheirRegionsColorsCagesAndPlacement() throws Exception {
        String[][] golden = {
            {"1", "0", "6057980c63692d5421feec38236c271aec59c425dbe3ddc3193ae713c4afab36"},
            {"1", "1", "cc49b57cc9a876918c2df4b40927d15ad094fcbe9beb257b6f7bd05fcb761161"},
            {"1", "7", "a14fc0127c6f2735a8fbd9ab8234a62bcf2551eaf9d8afa177c86cad5a213514"},
            {"1", "11", "05ba52779dc4400f4069962f400a3306fef5a0a4640842b86088513cd50a75ac"},
            {"2", "0", "4d294829eef8de65effe6ddf1d3a05699af3ba6b4d15773abb91232ada6b378a"},
            {"2", "1", "2b9a854ceb778d1bcebd8dced9198db32bf8d6d3374684736a3bd583979c7c3e"},
            {"2", "7", "2d97d9561d76f7a794e7dad1e756e2a0ae8d7176ed16abcaa9e306a0b8be15a5"},
            {"2", "11", "b3a525bb72b49c2e924245d6b37079ed56ddbc1d9f5e017c6b432091d1083c30"},
            {"3", "0", "aea3fd6807c27621399e9240d212108fc5254f1de9e5e55ea6c0dff5cca171c4"},
            {"3", "1", "c755f9a467630641df6050489faf90d578d04deda11e3ddb45cb1cc7dbe4d2db"},
            {"3", "7", "aeb763c930557317c02c76c4ef269e81be8b54db75e626f691d15535595401a0"},
            {"3", "11", "e5595cfd58053e875c8cd45ac436fac813fbeb2779643a66c595b48674ec96db"}
        };
        for (String[] expected : golden) {
            int difficulty = Integer.parseInt(expected[0]);
            long seed = Long.parseLong(expected[1]);
            assertEquals(expected[2], fingerprint(RayBlendLayout.create(0, difficulty, seed, 200, -50)),
                    "legacy difficulty=" + difficulty + ", seed=" + seed);
        }
    }

    /** Hash every stored plan field in a stable binary order. */
    static String fingerprint(RayBlendLayout layout) throws Exception {
        var bytes = new ByteArrayOutputStream();
        var out = new DataOutputStream(bytes);
        out.writeInt(layout.posY());
        out.writeInt(layout.length());
        out.writeInt(layout.rooms().size());
        for (var room : layout.rooms()) {
            for (int value : new int[]{room.profileIndex(), room.index(), room.gridSize(), room.edge(), room.x(), room.y(), room.z()})
                out.writeInt(value);
            for (int region : room.region()) out.writeInt(region);
            for (boolean[] flags : new boolean[][]{room.blocked(), room.start()})
                for (boolean flag : flags) out.writeBoolean(flag);
            for (var colors : List.of(room.color(), room.cage()))
                for (var color : colors) out.writeInt(color == null ? -1 : color.ordinal());
        }
        return HexFormat.of().formatHex(java.security.MessageDigest.getInstance("SHA-256").digest(bytes.toByteArray()));
    }
}
