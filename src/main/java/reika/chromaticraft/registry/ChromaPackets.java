	private final int wireId;
	private static final java.util.Map<Integer, ChromaPackets> BY_ID = reika.dragonapi.interfaces.PacketId.index(values());
	@Override public int wireId() { return wireId; }

	public final int numInts;
	public final PacketTypes type;

	ChromaPackets(int id) { this(id, 0); }

	ChromaPackets(int id, int size) { this(id, size, PacketTypes.DATA); }

	ChromaPackets(int id, int size, PacketTypes t) {
		wireId = id;
		numInts = size;
		type = t;
	}

	public static ChromaPackets getPacket(int id) {
		return reika.dragonapi.interfaces.PacketId.lookup(BY_ID, id);
	}

	public boolean hasData() {
		return numInts != 0;
	}

	public boolean variableData() {
		return numInts < 0;
	}

