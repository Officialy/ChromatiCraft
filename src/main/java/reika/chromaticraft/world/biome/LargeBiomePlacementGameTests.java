package reika.chromaticraft.world.biome;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.SplittableRandom;
import net.minecraft.core.Holder;
import net.minecraft.gametest.framework.GameTestHelper;
import net.minecraft.gametest.framework.TestEnvironmentDefinition;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.biome.MultiNoiseBiomeSource;
import net.minecraft.world.level.biome.Biomes;
import net.minecraft.world.level.biome.Climate;
import net.minecraft.tags.BiomeTags;
import net.minecraft.world.level.levelgen.densityfunction.SamplerContext;
import net.neoforged.neoforge.event.RegisterGameTestsEvent;
import reika.chromaticraft.ChromaGameTests;
import reika.chromaticraft.ChromatiCraft;
import reika.chromaticraft.registry.ChromaOptions;

/** Natural 26.3 climate lookup regression; no chunks or play saves are generated by the survey. */
public final class LargeBiomePlacementGameTests {
    public static void register(RegisterGameTestsEvent event, Holder<TestEnvironmentDefinition<?>> environment) {
        if (Boolean.getBoolean("chromaticraft.testNaturalWorld"))
            ChromaGameTests.register(event, environment, "large_biome_regions", 4000, LargeBiomePlacementGameTests::regions);
    }

    private static void regions(GameTestHelper helper) {
        var level = helper.getLevel();
        var source = level.getChunkSource().getGenerator().getBiomeSource();
        helper.assertTrue(source instanceof MultiNoiseBiomeSource, "requires the disposable natural overworld");
        var sampler = level.getChunkSource().randomState().createClimateSampler(SamplerContext.EMPTY_UNCACHED);
        var resolver = source.createResolver(sampler);
        var layout = new LargeBiomeLayout(level.getSeed(), ChromaOptions.getGlowingCliffsWeight(),
                ChromaOptions.getRainbowForestWeight());
        List<LargeBiomeLayout.Region> cliffs = new ArrayList<>(), rainbow = new ArrayList<>();
        int candidates = 0;
        long start = System.nanoTime();
        for (int cx = -12; cx <= 12; cx++) for (int cz = -12; cz <= 12; cz++) {
            var region = layout.candidate(cx, cz);
            if (region == null) continue;
            candidates++;
            var center = resolver.getNoiseBiome(region.x(), 80, region.z());
            if (!family(center, region.kind())) continue;
            (region.kind() == LargeBiomeLayout.Kind.CLIFFS ? cliffs : rainbow).add(region);
            int core = LargeBiomeLayout.CORE_QUARTS;
            for (int dx = -core; dx <= core; dx += 4) for (int dz = -core; dz <= core; dz += 4) {
                if (dx * dx + dz * dz <= core * core)
                    helper.assertTrue(family(resolver.getNoiseBiome(region.x() + dx, 80, region.z() + dz), region.kind()),
                            "accepted region must retain its full core at " + region.x() + ", " + region.z());
            }
            int x = Math.floorDiv(region.x(), 4) * 4, z = Math.floorDiv(region.z(), 4) * 4;
            var chunkResolver = source.createResolverForChunk(sampler, x, 80, z, 4, 1, 4);
            for (int dx = 0; dx < 4; dx++) for (int dz = 0; dz < 4; dz++)
                helper.assertTrue(chunkResolver.getNoiseBiome(x + dx, 80, z + dz)
                                .equals(resolver.getNoiseBiome(x + dx, 80, z + dz)),
                        "buffered chunk lookup and global biome lookup must agree");
        }
        helper.assertTrue(!cliffs.isEmpty() && rainbow.size() > cliffs.size(), "Cliffs must be rarer than Rainbow Forest");
        double[] distances = new double[441];
        int index = 0;
        double originSpacing = LargeBiomeLayout.CELL_QUARTS * 4 * .8;
        for (int x = -10; x <= 10; x++) for (int z = -10; z <= 10; z++) {
            double nearest = Double.POSITIVE_INFINITY;
            for (var region : cliffs)
                nearest = Math.min(nearest, Math.max(0, Math.hypot(x * originSpacing - region.x() * 4.0,
                        z * originSpacing - region.z() * 4.0) - region.radius() * 4.0));
            distances[index++] = nearest;
        }
        Arrays.sort(distances);
        ChromatiCraft.LOGGER.info("Large biome survey seed={}: candidates={}, cliffs={}, rainbow={}, nearest-cliffs blocks p25={}, median={}, p75={}, seconds={}",
                level.getSeed(), candidates, cliffs.size(), rainbow.size(), Math.round(distances[110]),
                Math.round(distances[220]), Math.round(distances[330]), (System.nanoTime() - start) / 1e9);
        helper.assertTrue(distances[220] >= 2000 && distances[220] <= 4000,
                "default cliff exploration should be measured in a few thousand blocks, median=" + distances[220]);
        var random = new SplittableRandom(0x4C414E4443415645L);
        int caves = 0, oceans = 0;
        for (int i = 0; i < 4096; i++) {
            int x = random.nextInt(-4096, 4096), z = random.nextInt(-4096, 4096);
            var underground = ((MultiNoiseBiomeSource)source).getNoiseBiome(sampler.sample(x, -8, z));
            if (underground.is(Biomes.DEEP_DARK) || underground.is(Biomes.LUSH_CAVES) || underground.is(Biomes.DRIPSTONE_CAVES)) {
                caves++;
                helper.assertTrue(resolver.getNoiseBiome(x, -8, z).equals(underground), "underground caves must survive the surface overlay");
            }
            var target = sampler.sample(x, 16, z);
            var surface = ((MultiNoiseBiomeSource)source).getNoiseBiome(new Climate.TargetPoint(target.temperature(),
                    target.humidity(), target.continentalness(), target.erosion(), 0, target.weirdness()));
            if (surface.is(BiomeTags.IS_OCEAN) || surface.is(Biomes.MUSHROOM_FIELDS)) {
                oceans++;
                var actual = resolver.getNoiseBiome(x, 80, z);
                helper.assertTrue(!family(actual, LargeBiomeLayout.Kind.CLIFFS) && !family(actual, LargeBiomeLayout.Kind.RAINBOW),
                        "protected surface terrain must not become a biome fragment");
            }
            var region = layout.candidate(Math.floorDiv(x, LargeBiomeLayout.CELL_QUARTS),
                    Math.floorDiv(z, LargeBiomeLayout.CELL_QUARTS));
            if (region == null || !region.contains(x, z)) {
                var actual = resolver.getNoiseBiome(x, 80, z);
                helper.assertTrue(!family(actual, LargeBiomeLayout.Kind.CLIFFS) && !family(actual, LargeBiomeLayout.Kind.RAINBOW),
                        "the old climate mappings must not leak fragments outside planned regions");
            }
        }
        helper.assertTrue(caves > 0 && oceans > 0, "preservation checks must actually encounter caves and protected terrain");
        ChromatiCraft.LOGGER.info("Large biome preservation: {} cave and {} ocean/mushroom samples passed", caves, oceans);
        helper.succeed();
    }

    private static boolean family(Holder<Biome> biome, LargeBiomeLayout.Kind kind) {
        return kind == LargeBiomeLayout.Kind.CLIFFS
                ? biome.is(ChromaBiomes.LUMINOUS_CLIFFS) || biome.is(ChromaBiomes.LUMINOUS_CLIFFS_SHORES)
                : biome.is(ChromaBiomes.RAINBOW_FOREST) || biome.is(ChromaBiomes.RAINBOW_STREAM);
    }
}
