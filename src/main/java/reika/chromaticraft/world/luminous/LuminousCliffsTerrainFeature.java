package reika.chromaticraft.world.luminous;

import net.minecraft.core.BlockPos;
import net.minecraft.core.QuartPos;
import net.minecraft.tags.BlockTags;
import net.minecraft.world.level.WorldGenLevel;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.chunk.ChunkAccess;
import net.minecraft.world.level.levelgen.Heightmap;
import net.minecraft.world.level.levelgen.NoiseBasedChunkGenerator;
import net.minecraft.world.level.levelgen.RandomState;
import net.minecraft.world.level.levelgen.feature.Feature;
import net.neoforged.neoforge.attachment.AttachmentType;
import net.neoforged.neoforge.registries.DeferredHolder;
import net.neoforged.neoforge.registries.DeferredRegister;
import net.neoforged.neoforge.registries.NeoForgeRegistries;
import reika.chromaticraft.registry.ChromaBlocks;
import reika.chromaticraft.registry.ChromaTieredPlants;
import reika.chromaticraft.world.GlowingCliffsColumnShaper;
import reika.chromaticraft.world.GlowingCliffsColumnShaper.BiomeKind;
import reika.chromaticraft.world.GlowingCliffsColumnShaper.Cell;

/**
 * V33a {@code BiomeGlowingCliffs.blendTerrainEdgesAndGenCliffs}: every Luminous Cliffs column is given
 * the shape {@link GlowingCliffsColumnShaper} computes, and (with {@code BIOMEBLEND}) every other column
 * within 16 blocks of the cliffs is pulled toward it. Upstream did this while the chunk was still a raw
 * block array; here it runs over the generated chunk, attached to every overworld biome so the blend
 * reaches the neighbours.
 *
 * <p>The 26.3 terrain hook applies this after the surface pass and before vanilla carvers. Noise caves
 * and aquifers below the original ground survive, and carvers subsequently cut the raised plateaus.
 * A saved chunk attachment prevents the biome feature from rebuilding the terrain over those caves.
 * Custom generators that do not use the noise terrain pipeline retain the feature fallback. The
 * blended neighbours keep their own surface blocks, moved to the new height, where upstream's order
 * (blend first, then the biome's surface pass) gave them their biome's surface.
 *
 * <p>Existing chunks are not reshaped, so cliffs generated by an earlier version meet new ones at a seam.
 */
public final class LuminousCliffsTerrainFeature implements Feature {
    public static final DeferredRegister<AttachmentType<?>> ATTACHMENTS =
            DeferredRegister.create(NeoForgeRegistries.ATTACHMENT_TYPES, "chromaticraft");
    private static final DeferredHolder<AttachmentType<?>, AttachmentType<Boolean>> SHAPED =
            ATTACHMENTS.register("cliffs_shaped", () -> AttachmentType.builder(() -> false)
                    .serialize(com.mojang.serialization.Codec.BOOL.fieldOf("shaped")).build());

    /** Both adapters address one active chunk; no neighbour chunk reads are needed for shaping. */
    private interface Columns {
        int getMinY();
        int getMaxY();
        int getHeight(Heightmap.Types type, int x, int z);
        BlockState getBlockState(BlockPos pos);
        void setBlock(BlockPos pos, BlockState state, int flags);
    }

    private record ChunkColumns(ChunkAccess chunk) implements Columns {
        public int getMinY() { return chunk.getMinY(); }
        public int getMaxY() { return chunk.getMaxY(); }
        public int getHeight(Heightmap.Types type, int x, int z) { return chunk.getHeight(type, x, z) + 1; }
        public BlockState getBlockState(BlockPos pos) { return chunk.getBlockState(pos); }
        public void setBlock(BlockPos pos, BlockState state, int flags) { chunk.setBlockState(pos, state, flags); }
    }

    private record LevelColumns(WorldGenLevel level) implements Columns {
        public int getMinY() { return level.getMinY(); }
        public int getMaxY() { return level.getMaxY(); }
        public int getHeight(Heightmap.Types type, int x, int z) { return level.getHeight(type, x, z); }
        public BlockState getBlockState(BlockPos pos) { return level.getBlockState(pos); }
        public void setBlock(BlockPos pos, BlockState state, int flags) { level.setBlock(pos, state, flags); }
    }

    public static boolean shapeBeforeCarvers(ChunkAccess chunk, NoiseBasedChunkGenerator generator,
            RandomState random, long seed) {
        if (chunk.getData(SHAPED)) return false;
        var resolver = generator.getBiomeSource().createUncachedResolver(random);
        var sampler = GlowingCliffsColumnShaper.forSeed(seed).new Sampler(
                new LuminousCliffsBiomeMask(resolver::getNoiseBiome, generator.getSeaLevel()));
        boolean changed = new LuminousCliffsTerrainFeature().shape(new ChunkColumns(chunk), sampler,
                chunk.getPos().getMinBlockX(), chunk.getPos().getMinBlockZ());
        chunk.setData(SHAPED, true);
        return changed;
    }

    public static final com.mojang.serialization.MapCodec<LuminousCliffsTerrainFeature> CODEC =
            com.mojang.serialization.MapCodec.unit(LuminousCliffsTerrainFeature::new);

    @Override
    public com.mojang.serialization.MapCodec<LuminousCliffsTerrainFeature> codec() {
        return CODEC;
    }

	public LuminousCliffsTerrainFeature() {

	}

	/** A sampler for this level, for any consumer that needs the cliffs' shape. */
	public static GlowingCliffsColumnShaper.Sampler sampler(WorldGenLevel level) {
		GlowingCliffsColumnShaper shaper = GlowingCliffsColumnShaper.forSeed(level.getSeed());
		return shaper.new Sampler(new LuminousCliffsBiomeMask(level::getUncachedNoiseBiome, level.getSeaLevel()));
	}

	@Override
	public boolean place(net.minecraft.world.level.WorldGenLevel world, net.minecraft.world.level.chunk.ChunkGenerator generator, net.minecraft.util.RandomSource random, net.minecraft.core.BlockPos origin) {
		WorldGenLevel level = world;
		int baseX = origin.getX() & ~15;
		int baseZ = origin.getZ() & ~15;
		ChunkAccess chunk = level.getChunk(baseX >> 4, baseZ >> 4);
		if (chunk.getData(SHAPED)) return false;
		GlowingCliffsColumnShaper.Sampler sampler = sampler(level);
		boolean changed = this.shape(new LevelColumns(level), sampler, baseX, baseZ);
		chunk.setData(SHAPED, true);
		return changed;
	}

	private boolean shape(Columns level, GlowingCliffsColumnShaper.Sampler sampler, int baseX, int baseZ) {
		if (!nearCliffs(sampler, baseX, baseZ))
			return false;
		boolean placed = false;
		for (int dx = 0; dx < 16; dx++) {
			for (int dz = 0; dz < 16; dz++) {
				int x = baseX + dx;
				int z = baseZ + dz;
				BiomeKind kind = sampler.biome(x, z);
				if (kind.isGlowingCliffs())
					placed |= this.shapeColumn(level, sampler, x, z);
				else
					placed |= this.blendColumn(level, sampler, x, z);
			}
		}
		return placed;
	}

	/** Whether any cliff biome lies within the outward blend distance of this chunk. */
	private static boolean nearCliffs(GlowingCliffsColumnShaper.Sampler sampler, int baseX, int baseZ) {
		int reach = GlowingCliffsColumnShaper.OUTWARD_SEARCH;
		for (int x = baseX - reach; x < baseX + 16 + reach; x += QuartPos.SIZE)
			for (int z = baseZ - reach; z < baseZ + 16 + reach; z += QuartPos.SIZE)
				if (sampler.biome(x, z).isGlowingCliffs())
					return true;
		return false;
	}

	private boolean shapeColumn(Columns level, GlowingCliffsColumnShaper.Sampler sampler, int x, int z) {
		GlowingCliffsColumnShaper.Column column = sampler.column(x, z);
		Cell[] cells = sampler.shaper().cells(column, x, z);
		int originalTop = level.getHeight(Heightmap.Types.OCEAN_FLOOR_WG, x, z) - 1;
		BlockPos.MutableBlockPos pos = new BlockPos.MutableBlockPos(x, 0, z);
		boolean changed = false;
		int top = Math.min(level.getMaxY() - 1, GlowingCliffsColumnShaper.HEIGHT + 64);
		for (int y = Math.max(0, level.getMinY()); y <= top; y++) {
			pos.setY(y);
			BlockState current = level.getBlockState(pos);
			if (current.is(Blocks.BEDROCK))
				continue;
			Cell cell = y < GlowingCliffsColumnShaper.HEIGHT ? cells[y] : Cell.AIR;
			BlockState target = this.stateFor(cell);
			if (cell == Cell.STONE && y <= originalTop && !isSurfaceMaterial(current))
				continue;
			if (current != target) {
				level.setBlock(pos, target, 2);
				changed = true;
			}
		}
		return changed;
	}

	private BlockState stateFor(Cell cell) {
		return switch (cell) {
			case AIR -> Blocks.AIR.defaultBlockState();
			case STONE -> Blocks.STONE.defaultBlockState();
			case DIRT -> Blocks.DIRT.defaultBlockState();
			case GRASS -> Blocks.GRASS_BLOCK.defaultBlockState();
			case WATER -> Blocks.WATER.defaultBlockState();
			case GLOW_DAISY -> ChromaBlocks.GLOW_DAISY.get().defaultBlockState();
			case SAPLING -> Blocks.OAK_SAPLING.defaultBlockState();
			case ROCK_FLOWER -> ChromaBlocks.tieredPlant(ChromaTieredPlants.ROCK_FLOWER).get().defaultBlockState();
			case GLOW_ROOT -> ChromaBlocks.GLOW_ROOT.get().defaultBlockState();
		};
	}

	/**
	 * V33a {@code blendEdge}. Raising fills with stone and lowering clears to water up to sea level and air
	 * above, as upstream did; the column's surface layers then go on top at the new height.
	 */
	private boolean blendColumn(Columns level, GlowingCliffsColumnShaper.Sampler sampler, int x, int z) {
		int y = level.getHeight(Heightmap.Types.OCEAN_FLOOR_WG, x, z) - 1;
		int top = sampler.blendedTop(x, z, y);
		if (top < 0 || top == y)
			return false;
		top = Math.max(level.getMinY() + 1, Math.min(top, level.getMaxY() - 1));
		BlockPos.MutableBlockPos pos = new BlockPos.MutableBlockPos(x, y, z);
		BlockState[] surface = new BlockState[4];
		int layers = 0;
		while (layers < surface.length) {
			pos.setY(y - layers);
			BlockState state = level.getBlockState(pos);
			if (!isSurfaceMaterial(state))
				break;
			surface[layers++] = state;
		}
		BlockState stone = Blocks.STONE.defaultBlockState();
		if (y < top) {
			for (int i = 0; i < layers; i++) {
				pos.setY(y - i);
				level.setBlock(pos, stone, 2);
			}
			for (int i = y + 1; i <= top; i++) {
				pos.setY(i);
				level.setBlock(pos, stone, 2);
			}
		}
		else {
			for (int i = y; i > top; i--) {
				pos.setY(i);
				level.setBlock(pos, i <= GlowingCliffsColumnShaper.SEA_LEVEL
						? Blocks.WATER.defaultBlockState() : Blocks.AIR.defaultBlockState(), 2);
			}
		}
		for (int i = 0; i < layers; i++) {
			pos.setY(top - i);
			level.setBlock(pos, surface[i], 2);
		}
		return true;
	}

	/** What the biome surface pass lays, which is what upstream's shaping replaced wholesale. */
	private static boolean isSurfaceMaterial(BlockState state) {
		return state.is(BlockTags.DIRT) || state.is(Blocks.GRASS_BLOCK) || state.is(BlockTags.SAND)
				|| state.is(Blocks.GRAVEL) || state.is(Blocks.SANDSTONE) || state.is(Blocks.RED_SANDSTONE)
				|| state.is(Blocks.SNOW_BLOCK) || state.is(Blocks.SNOW) || state.is(Blocks.CLAY)
				|| state.is(BlockTags.TERRACOTTA) || state.is(Blocks.PACKED_ICE) || state.is(Blocks.ICE);
	}
}
